/**
 * 按ID获取产品
 */
function getProductById(id) {
  return products.find(p => p.id === String(id)) || null;
}

/**
 * 按场景获取产品
 */
function getProductsByScene(sceneId) {
  return sceneProducts[sceneId] || [];
}

/**
 * 获取热销产品
 */
function getHotProducts(limit = 6) {
  return [...products].sort((a, b) => b.sales - a.sales).slice(0, limit);
}

/**
 * 获取所有产品
 */
function getAllProducts() {
  return products;
}

/**
 * 按关键词搜索
 */
function searchProducts(keyword, limit = 20) {
  if (!keyword) return products.slice(0, limit);
  const kw = keyword.toLowerCase();
  return products
    .filter(p => p.name.toLowerCase().includes(kw) || p.description.toLowerCase().includes(kw))
    .slice(0, limit);
}

